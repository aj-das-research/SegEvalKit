"""Write the PanTS result tables for the paper and the docs page from outputs/eval/pants/report/.

Every number is read from the CSV files written by benchmark_report.py; models whose
evaluation has not finished are listed as pending, so the script can be re-run at any time.

    python benchmarks/pants/write_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
REPORT = Path("/l/users/abhijit.das/SegEvalKit/outputs/eval/pants/report")
PAPER = ROOT / "paper/generated"
DOCS = ROOT / "docs/datasets/pants-benchmark.md"

MODELS = ["nnU-Net ResEnc-M", "MedFormer", "TotalSegmentator"]
SHORT = {"nnU-Net ResEnc-M": "nnU-Net", "MedFormer": "MedFormer", "TotalSegmentator": "TotalSeg."}
STRUCT = {"pancreas": "Pancreas", "pancreatic_lesion": "Pancreatic lesion", "liver": "Liver", "spleen": "Spleen",
          "kidney_left": "Kidney (L)", "kidney_right": "Kidney (R)", "stomach": "Stomach",
          "gall_bladder": "Gallbladder", "duodenum": "Duodenum", "aorta": "Aorta", "postcava": "IVC",
          "adrenal_gland_left": "Adrenal (L)", "adrenal_gland_right": "Adrenal (R)", "colon": "Colon",
          "common_bile_duct": "Common bile duct", "superior_mesenteric_artery": "SMA", "veins": "Veins"}
METRICS = [("dice", "DSC", True), ("nsd", "NSD", True), ("hd95", "HD95", False)]
FACTORS = ["CT phase", "scanner", "country", "slice thickness", "sex", "age", "tumour"]


def _read(name):
    p = REPORT / name
    try:
        return pd.read_csv(p)
    except (FileNotFoundError, pd.errors.EmptyDataError):
        return pd.DataFrame()


def fmt(v, metric):
    if not np.isfinite(v):
        return "--"
    return f"{v:.1f}" if metric == "hd95" else f"{v:.3f}"[1:] if v < 1 else "1.000"


def main():
    macro, pooled, pres = _read("macro.csv"), _read("pooled.csv"), _read("presence.csv")
    done = [m for m in MODELS if m in set(macro.get("model", []))]
    pending = [m for m in MODELS if m not in done]
    n_cases = json.loads((REPORT / "numbers.json").read_text())["n_cases"]
    structs = [s for s in STRUCT if s in set(macro["label"])]
    mean = macro.set_index(["model", "label", "metric"])["mean"]
    get = lambda m, s, k: float(mean.get((m, s, k), np.nan))  # noqa: E731

    # ---- paper: main table (means over cases, best per structure in bold)
    cols = "l" + "".join("|" + "c" * len(done) for _ in METRICS)
    arrow = {True: "$\\uparrow$", False: "$\\downarrow$"}
    head1 = " & ".join(f"\\multicolumn{{{len(done)}}}{{c}}{{{lab} {arrow[hi]}}}" for _, lab, hi in METRICS)
    head2 = " & ".join(SHORT[m] for _ in METRICS for m in done)
    rows = []
    for s in structs:
        cells = []
        for k, _, hi in METRICS:
            vals = [get(m, s, k) for m in done]
            fin = [v for v in vals if np.isfinite(v)]
            best = (max(fin) if hi else min(fin)) if len(fin) > 1 else None
            cells += [("\\textbf{%s}" if best is not None and v == best else "%s") % fmt(v, k) for v in vals]
        rows.append(f"{STRUCT[s]} & " + " & ".join(cells) + " \\\\")
    note = ("" if not pending else
            f"\\multicolumn{{{1 + len(done) * len(METRICS)}}}{{l}}{{\\footnotesize Pending: "
            + ", ".join(pending) + " (inference in progress).} \\\\\n")
    (PAPER / "pants_main_table.tex").write_text(
        "% Generated by benchmarks/pants/write_results.py from outputs/eval/pants/report/macro.csv.\n"
        f"\\small\\setlength{{\\tabcolsep}}{{4pt}}\n\\begin{{tabular}}{{{cols}}}\n\\toprule\n & {head1} \\\\\n"
        f" & {head2} \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n" + note + "\\end{tabular}\n")

    # ---- paper: macro vs pooled Dice
    pd_dice = pooled[pooled.metric == "pooled_dice"].set_index(["model", "label"])["value"]
    lrows = []
    for s in structs:
        if s == "pancreatic_lesion":
            continue
        cells = []
        for m in done:
            a, b = get(m, s, "dice"), float(pd_dice.get((m, s), np.nan))
            cells += [fmt(a, "dice"), fmt(b, "dice")]
        lrows.append(f"{STRUCT[s]} & " + " & ".join(cells) + " \\\\")
    lhead = " & ".join(f"\\multicolumn{{2}}{{c}}{{{SHORT[m]}}}" for m in done)
    (PAPER / "pants_levels_table.tex").write_text(
        "% Generated by benchmarks/pants/write_results.py (macro.csv, pooled.csv).\n"
        "\\vspace{2pt}\n"
        f"\\small\\setlength{{\\tabcolsep}}{{4pt}}\n\\begin{{tabular}}{{l{'|cc' * len(done)}}}\n\\toprule\n"
        f" & {lhead} \\\\\n & " + " & ".join(["macro", "pooled"] * len(done)) + " \\\\\n\\midrule\n"
        + "\n".join(lrows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- paper: presence
    if len(pres):
        prow = [f"{SHORT[r.model]} & {r.auc:.3f} & {r.sensitivity:.3f} & {r.specificity:.3f} & {int(r.n_pos)} & {int(r.n_neg)} \\\\"
                for r in pres.itertuples() if r.model in done]
        (PAPER / "pants_presence_table.tex").write_text(
            "% Generated by benchmarks/pants/write_results.py from presence.csv.\n"
            "\\small\n\\begin{tabular}{lccccc}\n\\toprule\nModel & AUC & Sens. & Spec. & $n_+$ & $n_-$ \\\\\n\\midrule\n"
            + "\n".join(prow) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- paper: cohorts (pancreas Dice per subgroup, Holm-adjusted p per model)
    crow, sig = [], {}
    summ = {m: _read(f"cohorts_{m.split()[0]}.csv") for m in done}
    tests = {m: _read(f"cohort_tests_{m.split()[0]}.csv") for m in done}
    for f in FACTORS:
        groups = None
        for m in done:
            d = summ[m]
            d = d[(d.factor == f) & (d.label == "pancreas") & (d.metric == "dice") & (~d.small) & (d.group != "(missing)")]
            groups = list(d.group) if groups is None else groups
        if not groups:
            continue
        order = {"≤ 1.25 mm": 0, "1.25–3 mm": 1, "> 3 mm": 2, "< 50": 0, "50–65": 1, "> 65": 2}
        groups = sorted(groups, key=lambda g: (order.get(g, 9), g))
        ps = []
        for m in done:
            t = tests[m]
            t = t[(t.factor == f) & (t.label == "pancreas") & (t.metric == "dice")]
            p = float(t.p_adjusted.iloc[0]) if len(t) else np.nan
            ps.append(p)
            sig[(m, f)] = p
        first = True
        for g in groups:
            vals = []
            for m in done:
                d = summ[m]
                r = d[(d.factor == f) & (d.group == g) & (d.label == "pancreas") & (d.metric == "dice")]
                vals.append(f"{r['mean'].iloc[0]:.3f}"[1:] if len(r) else "--")
            n = summ[done[0]]
            n = n[(n.factor == f) & (n.group == g) & (n.label == "pancreas") & (n.metric == "dice")]["n"]
            name = f"\\multirow{{{len(groups)}}}{{*}}{{{f[0].upper() + f[1:]}}}" if first else ""
            first = False
            gname = (g.replace("%", "\\%").replace("–", "--").replace("≤ ", "$\\le$\\,").replace("> ", "$>$\\,")
                     .replace("< ", "$<$\\,"))
            crow.append(f"{name} & {gname} & {int(n.iloc[0]) if len(n) else '--'} & " + " & ".join(vals) + " \\\\")
        crow.append(" & \\emph{adjusted $p$} & & " + " & ".join(
            ("$<\\!10^{-3}$" if p < 1e-3 else f"{p:.3f}") if np.isfinite(p) else "--" for p in ps) + " \\\\\n\\midrule")
    if crow:
        crow[-1] = crow[-1].replace("\\\\\n\\midrule", "\\\\")
        (PAPER / "pants_cohort_table.tex").write_text(
            "% Generated by benchmarks/pants/write_results.py (cohorts_*.csv, cohort_tests_*.csv).\n"
            f"\\small\\setlength{{\\tabcolsep}}{{4pt}}\n\\begin{{tabular}}{{llr{'c' * len(done)}}}\n\\toprule\n"
            "Factor & Group & $n$ & " + " & ".join(SHORT[m] for m in done) + " \\\\\n\\midrule\n"
            + "\n".join(crow) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- paper: macros
    mac = [f"\\newcommand{{\\pantsModelsDone}}{{{len(done)}}}",
           f"\\newcommand{{\\pantsPending}}{{{', '.join(pending) if pending else 'none'}}}"]
    # headline numbers quoted in the text: macro / pooled Dice and pancreas Dice per subgroup
    def cmd(name, val):
        mac.append(f"\\newcommand{{\\{name}}}{{{val}}}")
    tag = {"nnU-Net ResEnc-M": "NN", "MedFormer": "MF", "TotalSegmentator": "TS"}
    for m in done:
        for s_ in ("pancreas", "liver", "gall_bladder", "duodenum", "aorta"):
            k = s_.replace("_", "").replace("gallbladder", "Gall").capitalize()
            cmd(f"pants{tag[m]}{k}Macro", fmt(get(m, s_, "dice"), "dice"))
            cmd(f"pants{tag[m]}{k}Pooled", fmt(float(pd_dice.get((m, s_), np.nan)), "dice"))
        d = summ[m]
        for g, k in (("Venous", "Venous"), ("Non-contrast", "Noncon"), ("≤ 1.25 mm", "Thin"), ("> 3 mm", "Thick"),
                     ("tumour", "Tumour"), ("no tumour", "Notumour"), ("GE", "GE"), ("Siemens", "Siemens")):
            r = d[(d.group == g) & (d.label == "pancreas") & (d.metric == "dice")]
            if len(r):
                cmd(f"pants{tag[m]}Panc{k}", fmt(float(r["mean"].iloc[0]), "dice"))
        t = tests[m]
        t = t[(t.label == "pancreas") & (t.metric == "nsd") & (t.factor == "tumour")]
        if len(t):
            cmd(f"pants{tag[m]}TumourNSDeffect", f"{abs(float(t.effect.iloc[0])):.2f}")
    # paired comparisons, ranking schemes, lesion detection
    pairs = {("MedFormer", "TotalSegmentator"): "MFvsTS", ("nnU-Net ResEnc-M", "MedFormer"): "NNvsMF",
             ("nnU-Net ResEnc-M", "TotalSegmentator"): "NNvsTS"}
    for (a, b), tg in pairs.items():
        c = _read(f"compare_{a.split()[0]}_vs_{b.split()[0]}.csv")
        if not len(c):
            continue
        cmd(f"pants{tg}NSig", str(int(c.significant.sum())))
        cmd(f"pants{tg}NTests", str(len(c)))
        for s_ in ("pancreas", "spleen", "duodenum", "kidney_left"):
            k = s_.replace("_", "").capitalize()
            for met in ("dice", "hd95"):
                r = c[(c.label == s_) & (c.metric == met)]
                if len(r):
                    cmd(f"pants{tg}{k}{met.capitalize().replace('95', 'NF')}Better", f"{100 * r.frac_a_better.iloc[0]:.0f}")
        for met in ("dice", "nsd"):
            d = c[(c.metric == met)]
            cmd(f"pants{tg}MinBetter{met.capitalize()}", f"{100 * d.frac_a_better.min():.0f}")
            cmd(f"pants{tg}MaxBetter{met.capitalize()}", f"{100 * d.frac_a_better.max():.0f}")
    rk = _read("ranking.csv")
    if len(rk):
        flips = []
        for s_, d in rk[rk.scheme != "bootstrap"].groupby("structure", sort=False):
            w = {sc: d[(d.scheme == sc) & (d["rank"] == 1)].method.iloc[0] for sc in ("aggregate-then-rank", "rank-then-aggregate")}
            if w["aggregate-then-rank"] != w["rank-then-aggregate"]:
                flips.append(STRUCT[s_].lower().replace(" (l)", " (left)"))
        cmd("pantsRankFlips", " and ".join(flips) if flips else "none")
        cmd("pantsNRankFlips", str(len(flips)))
    for m in done:
        for s_, k in (("spleen", "Spleen"), ("pancreas", "Pancreas"), ("kidney_left", "Kidneyleft")):
            r = macro[(macro.model == m) & (macro.label == s_) & (macro.metric == "dice")]
            if len(r):
                cmd(f"pants{tag[m]}{k}DiceMedian", fmt(float(r["median"].iloc[0]), "dice"))
            r = macro[(macro.model == m) & (macro.label == s_) & (macro.metric == "hd95")]
            if len(r):
                cmd(f"pants{tag[m]}{k}HDMean", f"{float(r['mean'].iloc[0]):.1f}")
                cmd(f"pants{tag[m]}{k}HDMedian", f"{float(r['median'].iloc[0]):.1f}")
    for r in pres.itertuples() if len(pres) else []:
        if r.model in done:
            cmd(f"pants{tag[r.model]}PresAUC", f"{r.auc:.3f}")
            cmd(f"pants{tag[r.model]}PresSens", f"{r.sensitivity:.3f}")
            cmd(f"pants{tag[r.model]}PresSpec", f"{r.specificity:.2f}")
            cmd("pantsNPos", str(int(r.n_pos)))
            cmd("pantsNNeg", str(int(r.n_neg)))
    les = pooled[pooled.label == "pancreatic_lesion"].set_index(["model", "metric"])
    for m in done:
        for met, k in (("pooled_lesion_sensitivity", "LesSens"), ("pooled_lesion_precision", "LesPrec"),
                       ("fp_lesions_per_scan", "FPScan"), ("pooled_dice", "LesPooledDice")):
            if (m, met) in les.index:
                row = les.loc[(m, met)]
                cmd(f"pants{tag[m]}{k}", f"{row.value:.2f}")
                cmd(f"pants{tag[m]}{k}CI", f"{row.ci_low:.2f}--{row.ci_high:.2f}")
    # failure tail of HD95: cases above 50 mm and their share of the mean
    folder = {"nnU-Net ResEnc-M": "nnunet", "MedFormer": "medformer", "TotalSegmentator": "totalseg"}
    for m in done:
        w = pd.read_csv(REPORT.parent / folder[m] / "per_case_wide.csv")
        for s_, k in (("spleen", "Spleen"), ("kidney_left", "Kidneyleft"), ("pancreas", "Pancreas")):
            d = w.loc[w.label == s_, "hd95"].dropna()
            if len(d) and d.sum() > 0:
                cmd(f"pants{tag[m]}{k}HDTailN", str(int((d > 50).sum())))
                cmd(f"pants{tag[m]}{k}HDTailShare", f"{100 * d[d > 50].sum() / d.sum():.0f}")
                sub = w[(w.label == s_) & (w.hd95 > 50)]
                if "ref_empty" in sub:
                    cmd(f"pants{tag[m]}{k}HDTailRefEmpty", str(int(sub.ref_empty.astype(bool).sum())))
    (PAPER / "pants_macros.tex").write_text("% Generated by benchmarks/pants/write_results.py.\n" + "\n".join(mac) + "\n")

    # ---- docs page
    md = ["# PanTS benchmark", "",
          "Three official models, run here from their official code and checkpoints, on the **901 PanTS test CTs**, "
          "evaluated with SegEvalKit at every level: per case, pooled over the test set, by patient cohort and per patient.",
          ""]
    if pending:
        md += ['!!! info "Evaluation still running"',
               f"    Evaluated so far: {', '.join(done)} ({', '.join(str(n_cases[m]) for m in done)} cases). "
               f"{' and '.join(pending)} {'is' if len(pending) == 1 else 'are'} still running; the tables gain a "
               "column as each evaluation finishes.", ""]
    mv = {l.split("{")[1].lstrip("\\").rstrip("}"): l.split("}{")[1].rstrip("}") for l in mac if "}{" in l}
    if "pantsMFvsTSNSig" in mv:
        md += ["## What the numbers say", "",
               f"- **Paired cases, not means.** MedFormer has the higher Dice in {mv['pantsMFvsTSMinBetterDice']}–"
               f"{mv['pantsMFvsTSMaxBetterDice']} % of cases on each of the ten compared organs, yet the lower *mean* HD95 is "
               "TotalSegmentator's on most organs.",
               f"- **A failure tail drives the mean.** On the spleen, {mv['pantsMFSpleenHDTailN']} of 901 MedFormer cases "
               f"with HD95 > 50 mm make up {mv['pantsMFSpleenHDTailShare']} % of its mean HD95 (median "
               f"{mv['pantsMFSpleenHDMedian']} mm vs mean {mv['pantsMFSpleenHDMean']} mm); "
               f"{mv.get('pantsMFSpleenHDTailRefEmpty', '–')} of them are scans with an empty reference spleen mask in "
               "which MedFormer still predicts a spleen, scored at the image diagonal.",
               f"- **The ranking scheme picks the winner** on the {mv['pantsRankFlips']}: aggregate-then-rank and "
               "rank-then-aggregate disagree, while bootstrap resampling never changes either ranking.",
               f"- **Tumours:** MedFormer finds {mv.get('pantsMFLesSens', '–')} of reference lesions but only "
               f"{mv.get('pantsMFLesPrec', '–')} of its predicted lesions match a reference lesion ({mv.get('pantsMFFPScan', '–')} "
               f"false-positive lesions per scan); patient-level AUC {mv.get('pantsMFPresAUC', '–')}.",
               "- **Cohorts:** both models are less accurate on non-contrast and on GE scans; thin-slice scans score "
               "lower, which points to site and case-mix confounding rather than resolution.", ""]
    md += ["## Protocol", "",
           "| | |", "|---|---|",
           "| Reference | per-structure masks `LabelTe/<case>/segmentations/*.nii.gz`; pancreas = pancreas ∪ lesion |",
           "| Geometry | voxel correspondence (`alignment=\"ignore\"`): 227 of 901 cases carry label headers that disagree with the CT ([pitfall](../guide/pitfalls.md#header-mismatch)) |",
           "| Metrics | Dice, NSD at 2 mm, HD95, ASSD, volume errors; lesion-wise detection for lesion models |",
           "| Missing predictions | scored as empty |",
           "| Statistics | 95 % bootstrap CIs over cases; cohort tests Kruskal–Wallis / Mann–Whitney, Holm-corrected |", "",
           "## Organ segmentation (mean over cases)", ""]
    hdr = "| Structure | " + " | ".join(f"{lab} {SHORT[m]}" for _, lab, _ in METRICS for m in done) + " |"
    md += [hdr, "|---|" + "---:|" * (len(done) * len(METRICS))]
    for s in structs:
        md.append(f"| {STRUCT[s]} | " + " | ".join(fmt(get(m, s, k), k) for k, _, _ in METRICS for m in done) + " |")
    md += ["", "DSC and NSD: higher is better; HD95 in mm, lower is better.", "",
           "## Macro and pooled Dice", "",
           "The macro value averages per-case Dice (every patient weighs the same); the pooled value sums voxels over "
           "the test set (every voxel weighs the same). See [evaluation levels](../analysis/levels.md).", "",
           "| Structure | " + " | ".join(f"{SHORT[m]} macro | {SHORT[m]} pooled" for m in done) + " |",
           "|---|" + "---:|" * (2 * len(done))]
    for s in structs:
        if s != "pancreatic_lesion":
            md.append(f"| {STRUCT[s]} | " + " | ".join(
                f"{fmt(get(m, s, 'dice'), 'dice')} | {fmt(float(pd_dice.get((m, s), np.nan)), 'dice')}" for m in done) + " |")
    if len(pres):
        md += ["", "## Patient-level lesion detection", "",
               "| Model | AUC | Sensitivity | Specificity | positives | negatives |", "|---|---:|---:|---:|---:|---:|"]
        md += [f"| {r.model} | {r.auc:.3f} | {r.sensitivity:.3f} | {r.specificity:.3f} | {int(r.n_pos)} | {int(r.n_neg)} |"
               for r in pres.itertuples() if r.model in done]
    md += ["", "## Cohorts: pancreas Dice by subgroup", "",
           "| Factor | Group | n | " + " | ".join(SHORT[m] for m in done) + " |", "|---|---|---:|" + "---:|" * len(done)]
    for line in crow:
        cells = [c.strip() for c in line.replace("\\\\\n\\midrule", "").replace("\\\\", "").split("&")]
        cells = [c.replace("\\emph{adjusted $p$}", "*adjusted p*").replace("$<\\!10^{-3}$", "< 0.001").replace("\\%", "%")
                 .replace("--", "–").replace("$\\le$\\,", "≤ ").replace("$>$\\,", "> ").replace("$<$\\,", "< ")
                 for c in cells]
        if cells[0].startswith("\\multirow"):
            cells[0] = cells[0].split("{")[-1].rstrip("}")
        md.append("| " + " | ".join(cells) + " |")
    md += ["", "Subgroup differences are observational: a scanner or site may differ in case mix (phase, tumour "
           "size), so read them as hypotheses.", "",
           "## Reproduce", "", "```console",
           "$ sbatch benchmarks/pants/run_{nnunet,medformer,totalseg}.sbatch   # official inference",
           "$ sbatch --export=ALL,MODELS=totalseg slurm/pants_eval.sbatch        # evaluation + report",
           "$ python benchmarks/pants/write_results.py                          # these tables",
           "```", "",
           "MedFormer runs the official R-Super script with one upstream fix: its 3D padding swapped the slice and "
           "width axes, which made post-processing fail on 25 scans smaller than the training patch along the slice or width axis "
           "(`benchmarks/pants/patch_medformer.py`).", ""]
    DOCS.write_text("\n".join(md))
    print("done:", done, "pending:", pending)


if __name__ == "__main__":
    main()
