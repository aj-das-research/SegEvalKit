"""Render paper/generated/*.tex from experiment outputs (no number typed by hand)."""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SENS = ROOT / "outputs" / "sensitivity"
GEN = ROOT / "paper" / "generated"
NAMES = {"liver": "Liver", "kidney_left": "Left kidney", "aorta": "Aorta", "pancreas": "Pancreas", "veins": "Veins",
         "gall_bladder": "Gallbladder", "pancreatic_lesion": "Pancreatic lesion"}


def sensitivity_table():
    d = pd.read_csv(SENS / "sensitivity.csv")
    e = d[(d.perturbation == "erode") & (d.magnitude == 2) & d.metric.isin(["dice", "nsd", "hd95"])]
    med = e.groupby(["structure", "metric"]).value.median().unstack()
    vol = d.groupby("structure").ref_volume_ml.median()
    rows = []
    for s in vol.sort_values(ascending=False).index:
        rows.append(f"{NAMES[s]} & {vol[s]:.1f} & {med.loc[s, 'dice']:.3f} & {med.loc[s, 'nsd']:.3f} & "
                    f"{med.loc[s, 'hd95']:.2f} \\\\")
    body = "\n".join(rows)
    (GEN / "sensitivity_table.tex").write_text(
        "% Generated by benchmarks/paper_tables.py from outputs/sensitivity/sensitivity.csv. Do not edit.\n"
        "\\begin{tabular}{lrrrr}\n\\toprule\n"
        "Structure & Volume [mL] & Dice $\\uparrow$ & NSD$_{2\\,\\mathrm{mm}}$ $\\uparrow$ & HD95 [mm] $\\downarrow$ \\\\\n"
        "\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n")
    # Macros for numbers quoted in the text
    r = pd.read_csv(ROOT / "docs" / "assets" / "figures" / "sensitivity_summary.csv").set_index(["perturbation", "metric"])
    macros = {
        "sensDiceLiver": f"{med.loc['liver', 'dice']:.2f}", "sensDiceGall": f"{med.loc['gall_bladder', 'dice']:.2f}",
        "sensDiceVeins": f"{med.loc['veins', 'dice']:.2f}",
        "sensHDninetyMin": f"{med['hd95'].min():.1f}", "sensHDninetyMax": f"{med['hd95'].max():.1f}",
        "sensIslandDice": f"{100 * r.loc[('islands', 'dice'), 'rho']:.0f}",
        "sensIslandHDninety": f"{100 * r.loc[('islands', 'hd95'), 'rho']:.0f}",
        "sensHolesBtwo": f"{100 * r.loc[('holes', 'betti2_error'), 'rho']:.0f}",
        "sensHolesDice": f"{100 * r.loc[('holes', 'dice'), 'rho']:.0f}",
        "sensCutBzero": f"{100 * r.loc[('cut', 'betti0_error'), 'rho']:.0f}",
        "sensShiftRVD": f"{100 * r.loc[('shift', 'relative_volume_difference'), 'rho']:.0f}",
        "sensNCases": str(d.groupby("structure").case_id.nunique().min()),
        "sensNStructCases": str(len(d.groupby(["structure", "case_id"]))),
    }
    isl = d[(d.perturbation == "islands") & (d.magnitude == 2)]
    macros["sensIslandDiceMed"] = f"{isl[isl.metric == 'dice'].value.median():.3f}"
    macros["sensIslandHDMed"] = f"{isl[isl.metric == 'hd'].value.median():.1f}"
    (GEN / "sensitivity_macros.tex").write_text(
        "% Generated by benchmarks/paper_tables.py. Do not edit.\n"
        + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print("wrote sensitivity_table.tex, sensitivity_macros.tex", macros)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("what", nargs="*", default=["sensitivity"])
    a = ap.parse_args()
    if "sensitivity" in a.what:
        sensitivity_table()
